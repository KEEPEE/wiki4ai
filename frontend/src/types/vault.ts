/**
 * TypeScript type definitions for Vault entries.
 */

/**
 * Wire format for a v1 encrypted field, matching the backend's EncryptedField DTO:
 * ciphertext/iv are Base64-encoded strings, not raw byte arrays.
 *
 * v1 only. v2 folds the IV inside the blob, so a v2 field travels as a plain Base64
 * string (`usernameV2` / `passwordV2` / `notesV2`) and not in this wrapper.
 */
export interface EncryptedField {
  ciphertext: string;
  iv: string;
  salt?: string;
}

export interface VaultEntryData {
  username?: string;
  password: string;
  notes?: string;
}

export interface VaultEntry {
  id: number;
  title: string;
  url?: string;
  groupPath?: string;
  data: VaultEntryData;
  createdAt: string;
  updatedAt: string;
  /**
   * The row identity the v2 AAD is sealed against. Carried through from the wire
   * because rewriting a row means encrypting with *this* value: the column is not
   * updatable, so a fresh uuid would produce a blob the row cannot open.
   */
  entryUuid?: string;
  /**
   * False when the entry's secrets could not be opened with the keys this client
   * holds — a row written under an older salt, or one the migration had to skip.
   *
   * The alternative was a sentinel string in `data.password`, which the edit form
   * happily prefilled and saving wrote back as the user's new password. A flag cannot
   * be saved by accident: the form refuses to submit while it is false.
   */
  isReadable: boolean;
}

/**
 * The v2 columns a write carries instead of the v1 `*Encrypted` wrappers
 * (WIKI4AI-197 D2).
 */
export interface VaultV2WriteFields {
  /** Always 2 on a v2 write; absent means v1 to a backend that predates D2. */
  cryptoVersion?: 2;
  /** Fingerprint of the DEK the blobs were sealed under. Required on a v2 write. */
  keyId?: string;
  /** Row identity the AAD was built from, generated by the client before the INSERT. */
  entryUuid?: string;
  /** `iv(12) || ciphertext || tag`, Base64. */
  usernameV2?: string;
  passwordV2?: string;
  notesV2?: string;
}

export interface CreateVaultEntryDto extends VaultV2WriteFields {
  title: string;
  url?: string;
  groupPath?: string;
  usernameEncrypted?: EncryptedField;
  passwordEncrypted?: EncryptedField;
  notesEncrypted?: EncryptedField;
}

export interface UpdateVaultEntryDto extends VaultV2WriteFields {
  title?: string;
  url?: string;
  groupPath?: string;
  usernameEncrypted?: EncryptedField;
  passwordEncrypted?: EncryptedField;
  notesEncrypted?: EncryptedField;
}

export interface BackendVaultEntry {
  id: number;
  title: string;
  url?: string;
  groupPath?: string;
  usernameEncrypted: EncryptedField | null;
  passwordEncrypted: EncryptedField | null;
  notesEncrypted: EncryptedField | null;
  createdAt: string;
  updatedAt: string;

  // ==================== WIKI4AI-197 (D1): the v2 half of the row ====================

  /** 1 or 2. Which columns hold this row's secrets, and therefore how to read it. */
  cryptoVersion?: number | null;
  /** Row identity the v2 AAD is built from. */
  entryUuid?: string | null;
  /** Fingerprint of the DEK the v2 blobs were sealed under. */
  keyId?: string | null;
  usernameV2?: string | null;
  passwordV2?: string | null;
  notesV2?: string | null;
  /**
   * SHA-256 of the row's v1 bytes as the server holds them. The migrate endpoint
   * compares it as a compare-and-set, so a row that moved between the read and the
   * write is refused rather than quietly overwritten.
   */
  v1Digest?: string | null;
}

/** Response of `GET /vault/v2/params`, `POST /vault/v2/init-salt` and `init-key`. */
export interface VaultV2Params {
  initialized: boolean;
  /** Base64, 32 bytes, generated by the server and write-once. */
  salt: string | null;
  /** JSON, e.g. {"alg":"PBKDF2-HMAC-SHA256","iter":600000,"dkLen":256}. */
  kdf: string | null;
  /** The DEK sealed under a key derived from the raw password. Base64. */
  wrappedKey: string | null;
  keyId: string | null;
}

/** One row of a `POST /vault/v2/migrate` batch. */
export interface VaultV2MigrateEntry {
  id: number;
  expectedV1Digest: string;
  usernameV2?: string;
  passwordV2: string;
  notesV2?: string;
}

export interface VaultV2MigrateResult {
  migrated: number;
  ids: number[];
}
