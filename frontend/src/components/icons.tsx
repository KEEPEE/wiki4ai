/**
 * WIKI4AI-87: shared inline SVG icon set (Feather-style line icons).
 *
 * The dev/prod containers ship no emoji font, so emoji-as-icons render as
 * tofu boxes. All UI icons in the app are monochrome SVG line icons using
 * `stroke="currentColor"` — this module centralises the set so size/stroke/
 * alignment stay consistent (14–16 px default, 2px stroke, round caps/joins),
 * matching the existing icons in UserMenu / AdminUsersPage / MarkdownToolbar.
 */

export interface IconProps {
  /** Rendered width/height in px (default 16). */
  size?: number;
  className?: string;
}

interface BaseProps extends IconProps {
  children: React.ReactNode;
}

/** Shared <svg> wrapper: 24×24 viewBox, currentColor stroke, no fill. */
function LineIcon({ size = 16, className, children }: BaseProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

