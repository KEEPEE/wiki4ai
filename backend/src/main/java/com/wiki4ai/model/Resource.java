package com.wiki4ai.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Check;

import java.time.LocalDateTime;
import java.util.Objects;

/**
 * JPA entity of the capacity ledger of WIKI4AI-155 (migration V25).
 * <p>
 * A resource is a globally unique thing several actors compete for — a build runner,
 * a device, a licence seat. {@code capacity} is how many units of it exist,
 * {@code activeSlots} is how many are currently held. The pair is the invariant
 * {@code 0 <= activeSlots <= capacity}, and it is enforced in three places on purpose:
 * the DB CHECK constraints of V25, the same constraints mirrored as
 * {@link Check} here (the test profile builds the schema from the entities, so an
 * invariant that lived only in PostgreSQL could not be tested at all), and the
 * conditional UPDATE of {@code ResourceRepository.reserve} — the only statement that
 * raises the counter.
 *
 * <h2>Why there is no setter for {@code activeSlots}</h2>
 * The counter is not a field, it is a <b>result</b>: the sum of the slots of the live
 * reservations of this resource. A setter would make it writable by whatever code
 * holds the entity — a {@code PUT} body, a test fixture, a future service — and every
 * such write is a chance for the counter and the reservation rows to disagree. So the
 * entity exposes no setter: the counter grows only through
 * {@code ResourceRepository.reserve} and shrinks only through
 * {@code ResourceRepository.decrementSlots}, both of which are guarded UPDATEs whose
 * WHERE clause is the invariant itself. {@code ReservationAtomicityIntegrationTest}
 * asserts this shape by reflection, so it cannot rot back into existence.
 * <p>
 * The same reasoning keeps {@code createdAt} and {@code id} setter-free.
 *
 * <h2>Time columns</h2>
 * {@link LocalDateTime}, matching the {@code TIMESTAMP} (no time zone) column of V25
 * and every other entity here — SPEC rule 11b. {@code java.time.Instant} would map to
 * {@code TIMESTAMP WITH TIME ZONE} and the postgres profile ({@code ddl-auto: validate})
 * would refuse to start.
 *
 * <h2>The quoted {@code key} column</h2>
 * {@code key} is a keyword in H2 2.x — verified against h2-2.2.224, where
 * {@code CREATE TABLE ... (key VARCHAR(64) ...)} is a syntax error — and a non-reserved
 * keyword in PostgreSQL. V25 keeps the unquoted spelling because it runs on PostgreSQL;
 * the mapping here quotes the identifier (the backticks are the JPA/Hibernate quoting
 * convention, Hibernate then emits the dialect's own quote character) because the test
 * schema is generated by Hibernate against H2. Without the quotes the test schema of the
 * whole suite fails to build.
 */
@Entity
@Table(name = "resources")
@Getter
@NoArgsConstructor
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@Builder
@Check(name = "chk_resources_invariant",
        constraints = "capacity >= 1 AND active_slots >= 0 AND active_slots <= capacity")
public class Resource {

    /** Kind used when the caller does not name one (same default as the DB column). */
    public static final String DEFAULT_KIND = "generic";

    /** Capacity of a new resource (same default as the DB column). */
    public static final int DEFAULT_CAPACITY = 1;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Globally unique client-facing identifier (DB UNIQUE, V25). The reservation
     * endpoints are addressed by this, not by the numeric id, because a client that
     * wants to reserve something knows its name, not its row id.
     */
    @Column(name = "`key`", nullable = false, length = 64, unique = true)
    private String key;

    @Column(name = "name", nullable = false, length = 128)
    private String name;

    /** Free-form category. Not a CHECK constraint: kinds are a naming concern, not an invariant. */
    @Column(name = "kind", nullable = false, length = 32)
    private String kind;

    /** How many units of this resource exist. At least 1 (DB CHECK). */
    @Column(name = "capacity", nullable = false)
    private Integer capacity;

    /**
     * How many units are currently held. Written ONLY by the guarded UPDATEs of
     * {@code ResourceRepository} — see the class Javadoc for why there is no setter.
     */
    @Column(name = "active_slots", nullable = false)
    private Integer activeSlots;

    /** A disabled resource cannot be reserved; its held slots are left alone. */
    @Column(name = "enabled", nullable = false)
    private Boolean enabled;

    /** Free-form metadata. TEXT, like {@code WorkItem.body}. */
    @Column(name = "metadata", columnDefinition = "TEXT")
    private String metadata;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // ── Setters (service layer only; the entity has no blanket @Setter) ───────
    // Deliberately absent: setActiveSlots, setCreatedAt, setId.

    public void setKey(String key) {
        this.key = key;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setKind(String kind) {
        this.kind = kind;
    }

    /**
     * Set the capacity. Callers must go through {@code ResourceService.update}, which
     * refuses a capacity below the currently held slots — lowering it under a live
     * reservation would break the invariant through a plain PUT.
     */
    public void setCapacity(Integer capacity) {
        this.capacity = capacity;
    }

    public void setEnabled(Boolean enabled) {
        this.enabled = enabled;
    }

    public void setMetadata(String metadata) {
        this.metadata = metadata;
    }

    /** Units nobody is holding right now. A read of the invariant, never a writable field. */
    public int availableSlots() {
        int capacity = this.capacity == null ? 0 : this.capacity;
        int held = this.activeSlots == null ? 0 : this.activeSlots;
        return capacity - held;
    }

    @PrePersist
    protected void onCreate() {
        createdAt = LocalDateTime.now();
        // Defensive defaults: the DB columns have them, keep the Java side consistent
        // so a freshly built entity is already valid.
        if (kind == null || kind.isBlank()) {
            this.kind = DEFAULT_KIND;
        }
        if (capacity == null) {
            this.capacity = DEFAULT_CAPACITY;
        }
        if (enabled == null) {
            this.enabled = Boolean.TRUE;
        }
        if (activeSlots == null) {
            this.activeSlots = 0;
        }
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        Resource resource = (Resource) o;
        return id != null && Objects.equals(id, resource.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "Resource{" +
                "id=" + id +
                ", key='" + key + '\'' +
                ", name='" + name + '\'' +
                ", kind='" + kind + '\'' +
                ", capacity=" + capacity +
                ", activeSlots=" + activeSlots +
                ", enabled=" + enabled +
                '}';
    }
}
